"""Logging — one line per event, each tagged with the request it belongs to.

With several requests served at once, log lines interleave. A *request ID* (generated by
the API middleware, or taken from the client's ``X-Request-ID`` header) is stored in a
``ContextVar`` and stamped on every log line, so all the lines of one request can be
found with a single grep — and matched with what the client saw, since the same ID is
returned in the response headers.

A ``ContextVar`` (not a global) because each request runs in its own context: FastAPI
copies the context into the worker thread of a sync endpoint, so the ID follows the
request down into the agent's nodes without being passed around as a parameter.
"""

import logging
from contextvars import ContextVar

from copilot.config import settings

request_id_var: ContextVar[str] = ContextVar("request_id", default="-")

_FORMAT = "%(asctime)s %(levelname)-7s [%(request_id)s] %(name)s: %(message)s"


class _RequestIdFilter(logging.Filter):
    def filter(self, record: logging.LogRecord) -> bool:
        record.request_id = request_id_var.get()
        return True


def setup_logging() -> None:
    """Configure the ``copilot`` loggers (idempotent: safe to call more than once)."""
    logger = logging.getLogger("copilot")
    if any(isinstance(f, _RequestIdFilter) for h in logger.handlers for f in h.filters):
        return
    handler = logging.StreamHandler()
    handler.addFilter(_RequestIdFilter())
    handler.setFormatter(logging.Formatter(_FORMAT))
    logger.addHandler(handler)
    logger.setLevel(settings.log_level.upper())
    logger.propagate = False  # don't print twice through uvicorn's root handler
